-- Tabla 1: Automoviles
CREATE TABLE IF NOT EXISTS prq_automovil
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    color VARCHAR(50) NOT NULL,
    anio INTEGER NOT NULL,
    fabricante VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL,

    CONSTRAINT ck_prq_automovil_anio
        CHECK (anio BETWEEN 1900 AND 2100),

    CONSTRAINT ck_prq_automovil_tipo
        CHECK (tipo IN ('sedán', '4x4', 'moto'))
);

-- Tabla 2: Parqueos
CREATE TABLE IF NOT EXISTS prq_parqueo
(
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_provincia VARCHAR(100) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    precio_por_hora NUMERIC(10,2) NOT NULL,

    CONSTRAINT ck_prq_parqueo_precio
        CHECK (precio_por_hora > 0)
);

-- Tabla 3: Ingresos de automoviles
CREATE TABLE IF NOT EXISTS prq_ingreso_automovil
(
    consecutivo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_parqueo INTEGER NOT NULL,
    id_automovil INTEGER NOT NULL,
    fecha_hora_entrada TIMESTAMP NOT NULL,
    fecha_hora_salida TIMESTAMP NULL,

    CONSTRAINT fk_prq_ingreso_parqueo
        FOREIGN KEY (id_parqueo)
        REFERENCES prq_parqueo(id),

    CONSTRAINT fk_prq_ingreso_automovil
        FOREIGN KEY (id_automovil)
        REFERENCES prq_automovil(id),

    CONSTRAINT ck_prq_ingreso_fechas
        CHECK (
            fecha_hora_salida IS NULL
            OR fecha_hora_salida >= fecha_hora_entrada
        )
);

-- Indices para facilitar las consultas
CREATE INDEX IF NOT EXISTS idx_prq_ingreso_parqueo
    ON prq_ingreso_automovil(id_parqueo);

CREATE INDEX IF NOT EXISTS idx_prq_ingreso_automovil
    ON prq_ingreso_automovil(id_automovil);

CREATE INDEX IF NOT EXISTS idx_prq_ingreso_fecha
    ON prq_ingreso_automovil(fecha_hora_entrada);
